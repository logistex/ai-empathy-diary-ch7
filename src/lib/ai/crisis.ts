export type CrisisCheckResult = {
  /** 위기 표현이 하나라도 걸렸는지. */
  isCrisis: boolean;
  /** 걸린 규칙 이름. (규칙 목록의 문자열이며 일기 원문이 아니다. 로그에는 개수만 남기는 것을 권한다.) */
  matched: string[];
};

/** 유니코드 호환 형태로 통일하고 소문자로 바꾼다. (전각 문자, 조합형·분리형 한글 차이를 없앤다.) */
function foldCase(text: string): string {
  return text.normalize("NFKC").toLowerCase();
}

// 문자열로 만든 이유: tsconfig target이 ES2017이라 유니코드 속성 이스케이프를 리터럴로 쓸 수 없다.
// 보이지 않는 글자(너비 0 공백, 방향 표시 등)는 글 사이에 끼워 넣어 검사를 피할 수 있어서 먼저 지운다.
const INVISIBLE_PATTERN = new RegExp("[\\u200B-\\u200F\\u2060\\uFEFF\\u00AD]", "g");
// 한글 음절, 영문, 숫자만 남긴다. 공백·문장부호·이모지·자음/모음 낱자는 모두 지운다.
const NOT_WORD_PATTERN = new RegExp("[^0-9a-z\\uAC00-\\uD7A3]", "g");

/** 띄어쓰기는 두고 보이지 않는 글자만 지운 글. 짧은 단어 검사에 쓴다. */
function toSpaced(text: string): string {
  return foldCase(text).replace(INVISIBLE_PATTERN, "");
}

/** 공백·문장부호를 모두 지운 글. 긴 표현 검사에 쓴다. */
function toCompact(text: string): string {
  return toSpaced(text).replace(NOT_WORD_PATTERN, "");
}

/**
 * 일기 한 줄에서 위기 표현을 찾는다. 예외를 던지지 않고, 로그를 남기지 않는다.
 */
export function detectCrisis(content: string): CrisisCheckResult {
  const spaced = toSpaced(content);
  const compact = spaced.replace(NOT_WORD_PATTERN, "");

  const matched: string[] = [];
  for (const word of CRISIS_SHORT_KEYWORDS) {
    if (spaced.includes(word)) matched.push(word);
  }
  for (const phrase of CRISIS_PHRASES) {
    if (compact.includes(phrase)) matched.push(phrase);
  }
  return { isCrisis: matched.length > 0, matched };
}

